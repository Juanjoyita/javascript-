// operadores de comparacion

let d = 10
let e = 5

console.log(d == e) // igualdad
console.log(d != e) // desigualdad
console.log(d > e) // mayor que 
console.log(d < e) // menor que 
console.log(d >= e) // mayor o igual que 
console.log(d <= e) // menor o igual que

// operadores logicos

let f = true
let g = false

console.log(f && g) // operador AND devuelve true si ambos operandos son true
console.log(f || g) // operador OR devuelve true si al menos uno de los operandos es true
console.log(!f) // operador NOT devuelve el valor contrario del operando
console.log(!g) // operador NOT devuelve el valor contrario del operando    


