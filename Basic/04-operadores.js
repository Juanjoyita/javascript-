// operadores aritmetricos 
let a = 10
let b = 5

console.log (a + b ) // suma
console.log (a - b ) // resta 
console.log (a * b ) // multiplicacion 
console.log (a / b ) // division 
console.log (a % b ) // modulo o residuo 
console.log (a ** b ) // exponente o potencia   

console.log (a % b ) // el operador modulo o residuo devuelve el resto de la division entre a y b

console.log (a ** b ) // el operador exponente o potencia devuelve el resultado de elevar a a la potencia de b

a++ 
console.log(a) // el operador de incremento aumenta el valor de a en 1

b-- 
console.log(b) // el operador de decremento disminuye el valor de b en 1


